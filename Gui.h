/**
 * @file Gui.h
 * @brief High-performance Immediate-Mode GUI manager using Dear ImGui.
 * @author Ndongmo Silatsa Fabrice
 * @date Updated for NS2 Architecture (CEGUI Migration Clean Cut)
 */

#pragma once

#include <string>
#include <SDL3/SDL.h>
#include <imgui/imgui.h>
#include <glm/glm.hpp>

namespace NS2
{
	/**
	 * @class Gui
	 * @brief Encapsulates Dear ImGui initialization, framing contexts, and events.
	 */
	class Gui
	{
	public:
		Gui() = default;
		~Gui() { destroy(); }

		// Enforce strict resource management semantics over windowing states
		Gui(const Gui&) = delete;
		Gui& operator=(const Gui&) = delete;

		/**
		 * @brief Initializes the ImGui Context and links backend drivers for SDL3 and OpenGL3.
		 * @param window The active main window instance generated by your SDL3 framework.
		 * @param glContext The active OpenGL execution context handle bound to the main thread.
		 * @return True if backends initialize completely without errors, false otherwise.
		 */
		bool init(SDL_Window* window, SDL_GLContext glContext);

		/**
		 * @brief Fully clears the active root state layout elements.
		 *        Left for interface compatibility; immediate mode handles clearing automatically.
		 */
		void clear();

		/**
		 * @brief Fully destroys contexts and un-links hardware pipeline backends safely.
		 */
		void destroy();

		/**
		 * @brief Fired at the top of your frame iteration loops to build internal vertex buffers.
		 */
		void update();

		/**
		 * @brief Draws the generated widget layout sheets directly onto the screen.
		 *        Must be invoked at the absolute end of your frame pass, just before swapping buffers.
		 */
		void draw();

		/**
		 * @brief Directly pipelines raw incoming hardware SDL3 window inputs to ImGui.
		 * @param event The raw SDL3 event context passed from your central polling function.
		 * @return True if ImGui captured and consumed the event internally (e.g., clicking an ImGui button).
		 */
		bool onSDLEvent(SDL_Event& event);

		/** @brief Controls system hardware cursor display parameters. */
		void showMouseCursor();
		void hideMouseCursor();

		/** @brief Updates the global overlay font scale modifier. */
		void setFontScale(float scale);

	private:
		/**
		 * @brief Intercepts game controller and routing updates using native virtual keyboard key translations.
		 * @param event The raw SDL3 joystick event context data.
		 */
		void sdlJoystickTOimgui(const SDL_Event& event);

		ImGuiContext* m_context = nullptr; /**< Internal tracking handle tracking active widgets */
		SDL_Window* m_windowRef = nullptr;  /**< Saved non-owning pointer reference back to our main window */
		bool m_initialized = false;        /**< Context safety block initialization guard state flag */
	};
}
